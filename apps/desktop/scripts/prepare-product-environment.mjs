#!/usr/bin/env node

import fs from 'node:fs'
import path from 'node:path'

import { desktopRoot, loadProductEnvironment } from './product-environment.mjs'
import { productExecutableName } from './utils.mjs'

const product = loadProductEnvironment()
const outputDir = path.join(desktopRoot, 'build', 'managed-config')
const configYaml = `# Generated by scripts/prepare-product-environment.mjs. Do not edit.
# CUSTOM-BEGIN: lock the branded desktop to the company model gateway.
product:
  enabled: true
  brand_id: ${product.brandId}
  environment: ${product.environment}
  provider_id: ${product.providerId}
  gateway_origin: ${product.gatewayOrigin}
  update_manifest_url: ${product.updateManifestUrl}
  skill_hub_url: ${product.skillHubUrl}
  default_language: ${product.defaultLanguage}
  managed_image_generation: ${product.managedImageGeneration}
  sync_skill_usage: ${product.syncSkillUsage}
  allowed_messaging_platforms:${product.allowedMessagingPlatforms.length
    ? `\n${product.allowedMessagingPlatforms.map(platform => `    - ${platform}`).join('\n')}`
    : ' []'}
  disabled_capabilities:
${product.disabledCapabilities.map(capability => `    - ${capability}`).join('\n')}
model:
  provider: ${product.providerId}
  base_url: ${product.modelApiBaseUrl}
  api_mode: chat_completions
providers:
  ${product.providerId}:
    api: ${product.modelApiBaseUrl}
    key_env: LLANO_GATEWAY_API_KEY
    transport: chat_completions
model_catalog:
  enabled: false
# 运行期不许再从 PyPI 拉包。上游的 tools/lazy_deps.py 默认 allow_lazy_installs=true，
# 也就是说可选后端（TTS、Slack、Matrix、Bedrock…）会在第一次用到时现场 pip install。
# 对这个产品有三重问题：
#   1. 装进来的代码没过审计，公司机器上凭空多出一条 PyPI 出网通道
#   2. 那条通道绕开网关，DLP 看到的是 pip 而不是我们的流量
#   3. sidecar 冻成单文件之后根本没有可写的 site-packages，装也装不进去
# 要哪个后端，就在打包时进包。
security:
  allow_lazy_installs: false
# CUSTOM-END
`


// NSIS 卸载钩子。生成而不是手写，是因为里面两个名字（deep link 协议、userData
// 目录名）都得跟品牌配置走 —— 手写一份就是第二个真源。
//
// electron-builder 的 NSIS 模板不认识这两样东西：
//
// - 协议注册项是**应用在首次启动时自己写的**（`app.setAsDefaultProtocolClient`），
//   `build.protocols` 在 Windows 上只影响 macOS 的 Info.plist。卸载器不知道有这个
//   键，于是卸载之后 `llano-agent://` 继续指向一个已被删除的 exe（2026-08-25 实测）。
// - userData 目录卸载时故意保留（重装保住设置），但 `product-session.json` 里是
//   网关签发的设备 API Key —— 保住设置是一回事，保住一把还能用的凭据是另一回事。
//
//   ⚠️ 但**只在真卸载时删，更新时必须留**（`${ifNot} ${isUpdated}`）。
//   electron-builder 的 NSIS 在装新版之前会静默跑一遍旧版卸载器，所以这个宏在
//   更新路径上也会执行。2026-08-28 实测的后果：
//
//     1. 用户每更新一次就掉一次登录
//     2. 更严重的是**旧密钥永远不会被撤销** —— 删文件这条路上一次网络调用都没有，
//        而下面那个 `product-revocation-pending.json`（退出登录时写的墓碑，
//        专门用来在离线/崩溃后补做撤销）也被一起删掉了，等于把唯一的补救机制
//        也抹了。结果是每更新一次，网关上多一把**永久有效**的孤儿密钥。
//
//   `${isUpdated}` 由 electron-builder 的 uninstaller.nsh 提供，就在插入
//   customUnInstall 之后几行它自己也在用，同一作用域，可以直接引用。
//
//   ⚠️ 这只解决更新那一半。**真卸载仍然撤销不了** —— NSIS 里发不出 HTTP 请求。
//   那一半需要网关侧兜底（密钥有效期，或「同一账号同一设备只留最近 N 把」）。
//
// userData 目录名用的是 Electron 的 `app.getName()`，而 electron-builder 会把
// `build.productName` 注入进打包后的 package.json，所以两者是同一个字符串。
const nsisInclude = `; Generated by scripts/prepare-product-environment.mjs. Do not edit.
!include LogicLib.nsh

!macro customUnInstall
  ; 只在协议确实指向**本次安装目录**时才删。装了两份（安装目录可改）时，
  ; 卸掉其中一份不该把另一份的注册项一起带走。
  ReadRegStr $0 HKCU "Software\\Classes\\${product.deepLinkProtocol}\\shell\\open\\command" ""
  \${If} $0 == '"$INSTDIR\\${productExecutableName()}.exe" "%1"'
    DeleteRegKey HKCU "Software\\Classes\\${product.deepLinkProtocol}"
  \${EndIf}

  ; 只在真卸载时清凭据。更新路径也会跑这个宏（NSIS 装新版前先跑旧卸载器），
  ; 在那里删掉会话 = 用户掉登录 + 旧密钥永远撤销不掉。见文件头说明。
  \${ifNot} \${isUpdated}
    Delete "$APPDATA\\${product.productName}\\product-session.json"
    Delete "$APPDATA\\${product.productName}\\product-revocation-pending.json"
  \${endIf}
!macroend
`

fs.mkdirSync(path.join(desktopRoot, 'build'), { recursive: true })
fs.writeFileSync(path.join(desktopRoot, 'build', 'installer.nsh'), nsisInclude, 'utf8')

// `build/sidecar` 是 extraResources 的一项，目录不存在 electron-builder 直接报错。
// 探路包（LLANO_ALLOW_SIDECARLESS_BUILD=1）本来就没有 sidecar，所以这里只保证
// 目录在，不保证里面有东西 —— 「里面必须有东西」是 before-pack 的
// assertSidecarPresent 管的，那才是该拦住品牌发布构建的地方。
fs.mkdirSync(path.join(desktopRoot, 'build', 'sidecar'), { recursive: true })

fs.mkdirSync(outputDir, { recursive: true })
fs.writeFileSync(path.join(outputDir, 'config.yaml'), configYaml, 'utf8')
fs.writeFileSync(path.join(outputDir, 'product-environment.json'), `${JSON.stringify(product, null, 2)}\n`, 'utf8')

console.log(`[product] prepared ${product.environment} policy for ${product.modelApiBaseUrl}`)
